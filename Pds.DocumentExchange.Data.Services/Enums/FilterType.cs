namespace Pds.DocumentExchange.Data.Services.Enums
{
    /// <summary>
    /// Class containing the general filter types used by filtering services.
    /// </summary>
    public enum FilterType
    {
        /// <summary>
        /// The list filter type.
        /// </summary>
        ListFilter = 0,

        /// <summary>
        /// The date range filter type.
        /// </summary>
        DateRangeFilter = 1,

        /// <summary>
        /// The radio filter type.
        /// </summary>
        RadioFilter = 2,

        /// <summary>
        /// The text box filter type.
        /// </summary>
        TextBoxFilter = 3
    }
}